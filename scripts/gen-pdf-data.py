# Generates public/js/dta-pdf-data.js (glyph-name tables used by the PDF viewer). Facts only: standard encodings and the Adobe Glyph List.
import json, sys
from fontTools.cffLib import cffStandardStrings
from fontTools.encodings.StandardEncoding import StandardEncoding
from fontTools.encodings.MacRoman import MacRoman
from fontTools.agl import AGL2UV, LEGACY_AGL2UV, UV2AGL
import os, re
ALL = {k: (v[0] if isinstance(v, (list, tuple)) else v) for k, v in LEGACY_AGL2UV.items()}
ALL.update({k: (v[0] if isinstance(v, (list, tuple)) else v) for k, v in AGL2UV.items()})
for f in ('/usr/share/texlive/texmf-dist/fonts/map/glyphlist/glyphlist.txt','/usr/share/texlive/texmf-dist/fonts/map/glyphlist/texglyphlist.txt'):
    if os.path.exists(f):
        for ln in open(f, encoding='latin-1'):
            if ln.startswith('#') or ';' not in ln: continue
            n, u = ln.strip().split(';'); ALL.setdefault(n, int(re.split(r'[ ,]', u.strip())[0], 16))
std = list(cffStandardStrings)
stdenc = [n if n != ".notdef" else "" for n in StandardEncoding]
mac = [n if n != ".notdef" else "" for n in MacRoman]
win = []
for c in range(256):
    if c < 32: win.append(""); continue
    if c == 127 or c in (0x81, 0x8d, 0x8f, 0x90, 0x9d): win.append("bullet"); continue
    if c == 0xa0: win.append("space"); continue
    if c == 0xad: win.append("hyphen"); continue
    try: u = ord(bytes([c]).decode("cp1252"))
    except Exception: win.append(""); continue
    win.append(UV2AGL.get(u, "uni%04X" % u))
win[0x27] = "quotesingle"; win[0x60] = "grave"
agl = {n: u for n, u in ALL.items() if u < 0x3000 or 0xfb00 <= u <= 0xfb06}
agl_s = ",".join("%s:%x" % (n, u) for n, u in sorted(agl.items()))
out = """/* Generated by scripts/gen-pdf-data.py. Glyph-name tables (CFF standard strings, base encodings, Adobe Glyph List subset). */
(function (root, factory) { if (typeof module === "object" && module.exports) module.exports = factory(); else root.DTApdfData = factory(); })(typeof globalThis !== "undefined" ? globalThis : this, function () {
  var agl = null, A = %s;
  return {
    cffStd: %s,
    std: %s,
    mac: %s,
    win: %s,
    uni: function (name) {
      if (!agl) { agl = Object.create(null); A.split(",").forEach(function (e) { var i = e.indexOf(":"); agl[e.slice(0, i)] = parseInt(e.slice(i + 1), 16); }); }
      var u = agl[name]; if (u !== undefined) return u;
      var m = /^uni([0-9A-Fa-f]{4})/.exec(name) || /^u([0-9A-Fa-f]{4,6})$/.exec(name); if (m) return parseInt(m[1], 16);
      var d = name.indexOf("."); if (d > 0) return this.uni(name.slice(0, d)); return undefined;
    }
  };
});
""" % (json.dumps(agl_s), json.dumps(std), json.dumps(stdenc), json.dumps(mac), json.dumps(win))
open("public/js/dta-pdf-data.js", "w").write(out); print(len(out), len(agl))
